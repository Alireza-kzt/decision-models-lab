"""Immutable offline run records. No model downloads or remote requests."""
from __future__ import annotations
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import platform
import subprocess
import sys
from typing import Any
from .adapters import UniformAdapter
from .metrics import compute_metrics
from .schema import load_examples, load_predictions, nonempty_string, validate_probabilities

ROOT = Path(__file__).resolve().parents[1]

def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()

def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()

def save_json(path: Path, payload: Any) -> None:
    # No NaN/Infinity output; atomic replace within an already exclusive run folder.
    temp = path.with_name(path.name + ".tmp")
    temp.write_text(json.dumps(payload, indent=2, ensure_ascii=False, allow_nan=False) + "\n", encoding="utf-8")
    temp.replace(path)

def git_state(root: Path) -> dict[str, Any]:
    try:
        def get(*args: str) -> str:
            return subprocess.run(["git", "-C", str(root), *args], text=True, capture_output=True, check=True, timeout=10).stdout.strip()
        commit = get("rev-parse", "HEAD")
        dirty = bool(get("status", "--porcelain", "--untracked-files=normal"))
        return {"commit": commit, "dirty": dirty}
    except (OSError, subprocess.SubprocessError):
        return {"commit": None, "dirty": None}

def code_hashes() -> dict[str, str]:
    return {str(p.relative_to(ROOT)).replace("\\", "/"): sha256(p) for p in sorted((ROOT / "decision_lab").glob("*.py"))}

def evaluate_run(*, dataset: Path, predictions: Path | None, out: Path, kind: str, model_id: str, revision: str, bins: int = 10, threshold: float = 0.8, seed: int | None = None) -> dict[str, Any]:
    if kind not in {"demonstration", "research"}:
        raise ValueError("Unknown run kind")
    nonempty_string(model_id, "model_id")
    nonempty_string(revision, "revision")
    out.mkdir(parents=True, exist_ok=False)
    manifest: dict[str, Any] = {
        "schema_version": "1.0", "run_id": out.name, "kind": kind, "status": "running",
        "started_at_utc": utc_now(), "model_id": model_id, "model_revision_declared": revision,
        "provider_execution": "none; evaluates stored predictions or uniform fixture",
        "seed": seed, "seed_role": "metadata only; no training or randomness in core",
        "git": git_state(ROOT), "code_hashes": code_hashes(),
        "environment": {"python": sys.version, "platform": platform.platform(), "machine": platform.machine()},
        "metric_config": {"bins": bins, "threshold": threshold},
        "input_files": {"dataset": str(dataset), "predictions": str(predictions) if predictions else None},
        "network_access": False,
    }
    save_json(out / "manifest.json", manifest)
    try:
        if kind == "research" and (manifest["git"]["commit"] is None or manifest["git"]["dirty"]):
            raise ValueError("Research evaluation requires a clean committed Git checkout")
        examples = load_examples(dataset, evaluation=True)
        if kind == "research" and any(ex.split == "demonstration" for ex in examples):
            raise ValueError("Demonstration data cannot be labelled as research")
        if predictions is None:
            if kind != "demonstration" or model_id != "uniform-demo" or revision != "v1":
                raise ValueError("Uniform generation is restricted to the named demonstration model")
            adapter = UniformAdapter()
            probs = {ex.id: validate_probabilities(adapter.predict(ex.state, ex.question, ex.options), set(ex.options)) for ex in examples}
            manifest["prediction_provenance"] = "generated by non-learned uniform adapter"
        else:
            probs = load_predictions(predictions, examples)
            manifest["prediction_provenance"] = "user-supplied stored predictions; provider provenance not independently verified"
            manifest["predictions_input_sha256"] = sha256(predictions)
        manifest["dataset_sha256"] = sha256(dataset)
        manifest["split"] = examples[0].split
        manifest["n_groups"] = len({ex.group_id for ex in examples})
        normalized = out / "predictions.jsonl"
        normalized.write_text("".join(json.dumps({"id": ex.id, "probabilities": probs[ex.id]}, ensure_ascii=False, allow_nan=False) + "\n" for ex in examples), encoding="utf-8")
        metrics = compute_metrics(examples, probs, bins=bins, threshold=threshold)
        save_json(out / "metrics.json", metrics)
        manifest["saved_predictions_sha256"] = sha256(normalized)
        manifest["metrics_sha256"] = sha256(out / "metrics.json")
        manifest["status"] = "completed"
        manifest["completed_at_utc"] = utc_now()
        save_json(out / "manifest.json", manifest)
        title = "DEMONSTRATION ONLY — not model research" if kind == "demonstration" else "Offline research evaluation — inspect provenance and protocol"
        report = f"# {title}\n\nModel identifier: `{model_id}`; declared revision: `{revision}`.\n\nN={metrics['n']}; accuracy={metrics['accuracy']:.6f}; NLL={metrics['nll']:.6f}; multiclass-sum Brier={metrics['brier_multiclass_sum']:.6f}.\n\nNo real-time provider call, statistical confidence interval, training run or latency benchmark occurred. Inspect manifest.json, predictions.jsonl and metrics.json.\n"
        (out / "report.md").write_text(report, encoding="utf-8")
        return metrics
    except Exception as exc:
        manifest["status"] = "failed"
        manifest["completed_at_utc"] = utc_now()
        manifest["error_type"] = type(exc).__name__
        # Raw payloads and exception messages may contain sensitive data.
        save_json(out / "manifest.json", manifest)
        raise
